    private static final TIntObjectMap<GameVersion> BY_PROTOCOL_VERSION = new TIntObjectHashMap<>();
    private static final Map<String, GameVersion> BY_NAME = new HashMap<>();

    static {
        for (GameVersion version : values()) {
            BY_PROTOCOL_VERSION.put(version.getVersion(), version);

            for (String name : version.names) {
                BY_NAME.put(name.toLowerCase(), version);
            }
        }
    }

    @Getter
    private final int version;
    private final String[] names;

    GameVersion(int version, String... names) {
        this.version = version;
        this.names = names;
    }

    public String getName() {
        return names[0];
    }

    @Override
    public String toString() {
        return getName();
    }

    public static GameVersion getByProtocolNumber(int id) {
        GameVersion version = BY_PROTOCOL_VERSION.get(id);

        if (version == null) {
            return UNKNOWN;
        }

        return version;
    }

    public static GameVersion getByName(String name) {
        return BY_NAME.getOrDefault(name.toLowerCase(), UNKNOWN);
    }

